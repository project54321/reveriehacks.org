// Refreshes the baked-in copy of the country sheet.
//
//   npm run countries
//
// Same role as the DEVPOST_FALLBACK constants: what the Impact map draws when
// /api/countries is unreachable — offline, a cold deploy, or Google changing
// the sheet's shape. A failure here means the sheet moved and the parser in
// api/_countries.js needs updating.

import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

import { scrapeCountryStats, SHEET_VIEW_URL } from '../api/_countries.js';

console.log(`Reading ${SHEET_VIEW_URL}\n`);

const { countries, totals } = await scrapeCountryStats();

// Ordered most-registrations-first, but only the shading step comes back — the
// counts themselves are never published. See api/_countries.js.
for (const row of countries.slice(0, 8)) {
  console.log(`  ${row.name.padEnd(26)}${'▇'.repeat(row.share + 1)}`);
}

console.log(`  ${`… ${countries.length - 8} more`.padEnd(26)}`);
console.log(
  `\n  ${totals.countries} countries, ${totals.registrants.toLocaleString('en-US')} registrants, ` +
    `${totals.submitters.toLocaleString('en-US')} submitters, ${totals.unknown} unattributed`,
);

const rows = countries
  .map((c) => `  { name: ${JSON.stringify(c.name)}, share: ${c.share} },`)
  .join('\n');

const file = `// GENERATED by scripts/generate-country-fallback.mjs — run \`npm run countries\`.
//
// A snapshot of the published country sheet, used when /api/countries can't be
// reached. The live endpoint replaces it as soon as it answers.
//
// Countries carry a shading step, not a headcount: the per-country registration
// figures are deliberately not published, here or over the wire.

import type { CountryStats } from './countries';

export const COUNTRY_FALLBACK: CountryStats = {
  countries: [
${rows}
  ],
  totals: {
    countries: ${totals.countries},
    registrants: ${totals.registrants},
    submitters: ${totals.submitters},
    unknown: ${totals.unknown},
  },
};
`;

const out = resolve(import.meta.dirname, '../src/app/data/countries-fallback.ts');
await writeFile(out, file);

console.log(`\nwrote ${out}`);
